CREATE TABLE PIZZA_SALES (
	PIZZA_ID INTEGER PRIMARY KEY,
	ORDER_ID INTEGER,
	PIZZA_NAME_ID TEXT,
	QUANTITY INTEGER,
	ORDER_DATE DATE,
	ORDER_TIME TIME,
	UNIT_PRICE NUMERIC(10, 2),
	TOTAL_PRICE NUMERIC(10, 2),
	PIZZA_SIZE VARCHAR(10),
	PIZZA_CATEGORY VARCHAR(50),
	PIZZA_INGREDIENTS TEXT,
	PIZZA_NAME TEXT
);

SELECT
	*
FROM
	PIZZA_SALES;

-- 1) Find out Pizza sales Total Revenue.
SELECT
	SUM(TOTAL_PRICE) AS TOTAL_REVENUE
FROM
	PIZZA_SALES;

-- 2) Find out Total orders.
SELECT
	COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS
FROM
	PIZZA_SALES;

-- 3) Average Order value.
SELECT
	CAST(
		CAST(SUM(TOTAL_PRICE) AS DECIMAL(10, 2)) / CAST(COUNT(DISTINCT ORDER_ID) AS DECIMAL(10, 2)) AS DECIMAL(10, 2)
	) AS AVG_ORDER_VALUE
FROM
	PIZZA_SALES;

-- 4) Total Pizzas Sold.
SELECT
	SUM(QUANTITY) AS TOTAL_PIZZA_SOLD
FROM
	PIZZA_SALES;

-- 5) Average Pizzas Per Order.
SELECT
	SUM(QUANTITY) / COUNT(DISTINCT ORDER_ID) AS AVG_PIZZA_PER_ORDER
FROM
	PIZZA_SALES;

