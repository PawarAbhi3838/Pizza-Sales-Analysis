-- Analysis
-- 1) Monthly Trend for total Revenue.
SELECT
	TO_CHAR(ORDER_DATE, 'MONTH') AS MONTH,
	SUM(TOTAL_PRICE) AS TOTAL_REVENUE
FROM
	PIZZA_SALES
GROUP BY
	TO_CHAR(ORDER_DATE, 'MONTH');

-- 2) Daily Trand for Total Orders.
SELECT
	TO_CHAR(ORDER_DATE, 'DAY') AS DAY,
	COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDER
FROM
	PIZZA_SALES
GROUP BY
	TO_CHAR(ORDER_DATE, 'DAY');

-- 3) Percentage of Sales by Pizza Category.
SELECT
	PIZZA_CATEGORY,
	SUM(TOTAL_PRICE) AS TOTAL_REVENUE,
	CAST(
		SUM(TOTAL_PRICE) * 100 / (
			SELECT
				SUM(TOTAL_PRICE)
			FROM
				PIZZA_SALES
		) AS DECIMAL(10, 2)
	) AS PCT
FROM
	PIZZA_SALES
GROUP BY
	PIZZA_CATEGORY;

-- 4) Percentage of Sales by Pizza Size.
SELECT
	PIZZA_SIZE,
	SUM(TOTAL_PRICE) AS TOTAL_REVENUE,
	CAST(
		SUM(TOTAL_PRICE) * 100 / (
			SELECT
				SUM(TOTAL_PRICE)
			FROM
				PIZZA_SALES
		) AS DECIMAL(10, 2)
	) AS PCT
FROM
	PIZZA_SALES
GROUP BY
	PIZZA_SIZE;

-- 5) Total Pizza sold by pizza size and category.
SELECT
	PIZZA_SIZE,
	SUM(QUANTITY) AS TOTAL_PIZZA_SOLD
FROM
	PIZZA_SALES
GROUP BY
	PIZZA_SIZE;

SELECT
	PIZZA_CATEGORY,
	SUM(QUANTITY) AS TOTAL_PIZZA_SOLD
FROM
	PIZZA_SALES
GROUP BY
	PIZZA_CATEGORY;

-- 6) Revenue by Pizza Name.
SELECT
	PIZZA_NAME,
	SUM(TOTAL_PRICE) AS TOTAL_REVENUE
FROM
	PIZZA_SALES
GROUP BY
	PIZZA_NAME
ORDER BY
	TOTAL_REVENUE DESC
LIMIT
	5;

-- 7. Bottom 5 Pizzas by Revenue
SELECT
	PIZZA_NAME,
